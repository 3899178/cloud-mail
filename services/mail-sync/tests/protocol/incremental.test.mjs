import test from 'node:test';
import assert from 'node:assert/strict';
import { imapFixture, wireMime } from './fixtures.mjs';
import { fixture, owner } from '../core/helpers.mjs';
import { openStore } from '../../src/core/store.mjs';
import { createImapSession } from '../../src/providers/imap.mjs';
import { createSyncEngine } from '../../src/sync/engine.mjs';

for (const condstore of [true, false]) test(`real IMAP persisted inventory avoids unchanged history transfer (CONDSTORE=${condstore})`, async t => {
  const imap = await imapFixture(t); imap.state.condstore = condstore;
  const f = await fixture(t); let store = f.store; let now = Date.now();
  const a = store.accounts.create(owner, { id: 'incremental', provider: 'imap', address: 'fixture@example.test' });
  const rows = imap.state.folders.get('Archive');
  for (let i = 1; i <= 250; i++) rows.push({ uid: i, key: `history-${i}`, subject: 'history', unread: true, raw: wireMime(`history-${i}`), internalDate: '01-Jan-2020 12:00:00 +0000' });
  const registry = { open: () => createImapSession({ account: a, clock: () => now, config: { imap: { host: 'fixture.test', port: imap.port, secure: true } }, auth: async () => ({ user: a.address, pass: 'fixture' }), tlsOptions: { ca: imap.ca }, endpointResolver: async () => ({ host: '127.0.0.1', port: imap.port, servername: 'fixture.test' }) }) };
  const check = await registry.open(); await check.close();
  let engine = createSyncEngine({ store, registry });
  const sync = () => engine.syncAccount({ ownerId: owner, accountId: a.id });
  assert.equal((await sync()).status, 'active');
  assert.equal(store.sources.catalog(owner, a.id).length, 250);
  assert.equal(store.messages.list(owner).items.length, 0, 'historical inventory retained without importing old bodies');
  store.close(); store = openStore(f.options); t.after(() => store.close()); engine = createSyncEngine({ store, registry });
  imap.state.metadataRows = 0; imap.state.commands.length = 0;
  assert.equal((await sync()).status, 'active');
  assert.equal(imap.state.metadataRows, 0, 'restart unchanged polling must not fetch history envelopes');
  const requests = imap.state.commands.filter(c => / FETCH /.test(c)).length;
  if (condstore) assert.equal(requests, 0, 'unchanged MODSEQ must not read any historical rows');
  t.diagnostic(`unchanged CONDSTORE=${condstore}: metadata-envelope rows=0; FETCH requests=${requests}; total commands=${imap.state.commands.length}`);
  const beforePartial = store.checkpoints.get(owner, a.id, 'Archive');
  imap.state.modseq = 2;
  if (condstore) imap.state.omitSearchUid = 1; else imap.state.omitFetchUid = 1;
  assert.equal((await sync()).status, 'error', 'partial UID inventory cannot authorize pruning');
  assert.deepEqual(store.checkpoints.get(owner, a.id, 'Archive'), beforePartial);
  assert.equal(store.sources.catalog(owner, a.id).length, 250);
  delete imap.state.omitSearchUid; delete imap.state.omitFetchUid;
  rows.push({ uid: 251, key: 'new-old-date', subject: 'new-old-date', unread: true, raw: wireMime('new-old-date'), modseq: 2, internalDate: '01-Jan-2020 12:00:00 +0000' }); imap.state.modseq = 2;
  imap.state.omitEnvelopeUid = 251;
  assert.equal((await sync()).status, 'error', 'missing newly assigned UID envelope is an incomplete sweep');
  assert.deepEqual(store.checkpoints.get(owner, a.id, 'Archive'), beforePartial);
  assert.equal(store.sources.catalog(owner, a.id).length, 250);
  assert.equal(store.messages.list(owner).items.length, 0);
  delete imap.state.omitEnvelopeUid;
  assert.equal((await sync()).status, 'active');
  assert.equal(store.messages.list(owner).items.length, 1, 'new UID with old date admitted');
  if (condstore) assert.equal(imap.state.metadataRows, 1, 'only newly changed envelope transferred');
  const saved = store.messages.list(owner).items[0];
  rows[250].unread = false; rows[250].modseq = 3; imap.state.modseq = 3;
  assert.equal((await sync()).status, 'active'); assert.equal(store.messages.get(owner, saved.ref).unread, false);
  const [moved] = rows.splice(250, 1); imap.state.folders.get('Rules').push({ ...moved, uid: 1, modseq: 4 }); imap.state.modseq = 4;
  assert.equal((await sync()).status, 'active'); assert.equal(store.messages.get(owner, saved.ref).folder, 'Rules');
  imap.state.folders.get('Rules').length = 0; imap.state.modseq = 5;
  assert.equal((await sync()).status, 'active'); assert.equal(store.messages.list(owner).items.length, 0);
  assert.equal(store.sources.catalog(owner, a.id).length, 250);
  now += 300001; imap.state.metadataRows = 0;
  assert.equal((await sync()).status, 'active'); assert.equal(imap.state.metadataRows, 250, 'periodic audit reads the complete inventory');
  const checkpoint = store.checkpoints.get(owner, a.id, 'Archive');
  imap.state.validity = '101'; rows[0].key = 'unmatched-reset-history';
  assert.equal((await sync()).errorCode, 'RESYNC_REQUIRED');
  assert.deepEqual(store.checkpoints.get(owner, a.id, 'Archive'), checkpoint);
  assert.equal(store.sources.catalog(owner, a.id).length, 250);
  store.close();
});


